"""Both packaging modes ship complete offline help without generated caches."""

from configparser import ConfigParser
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest
import zipfile

POWERSHELL = str(Path(os.environ.get("SystemRoot", "C:/Windows")) /
                 "System32/WindowsPowerShell/v1.0/powershell.exe")


def copy_help(source, target):
    """Preserve the repository layout used by the packaging command."""
    shutil.copytree(source.parent / "docs" / "help", target.parent / "docs" / "help")


@unittest.skipUnless(Path(POWERSHELL).is_file(), "Packaging checks require Windows PowerShell")
class HelpPackageTests(unittest.TestCase):
    def test_read_failure_does_not_leave_an_incomplete_archive(self):
        source = Path(__file__).resolve().parents[1]
        package = "savonia_responsible_forest_planning_tool"
        with tempfile.TemporaryDirectory(prefix="Metsä failed package ") as folder:
            root = Path(folder)
            root = root / "qgis_plugin"
            root.mkdir()
            copy_help(source, root)
            shutil.copy2(source / "package.ps1", root / "package.ps1")
            target = root / package
            shutil.copytree(source / package, target, ignore=shutil.ignore_patterns("__pycache__"))
            locked = str(target / "LICENSE").replace("'", "''")
            script = str(root / "package.ps1").replace("'", "''")
            command = ("$locked = [System.IO.File]::Open('" + locked +
                       "', 'Open', 'ReadWrite', 'None'); try { & '" + script +
                       "' } finally { $locked.Dispose() }")
            result = subprocess.run([POWERSHELL, "-NoProfile", "-ExecutionPolicy", "Bypass", "-Command", command],
                                    capture_output=True, text=True)
            self.assertNotEqual(result.returncode, 0)
            self.assertEqual(list((root / "dist").glob("*.zip")), [])
            self.assertTrue((target / "LICENSE").is_file())

    def test_incrementing_archive_changes_only_disposable_version_and_keeps_resources(self):
        source = Path(__file__).resolve().parents[1]
        package = "savonia_responsible_forest_planning_tool"
        original = (source / package / "metadata.txt").read_bytes()
        parser = ConfigParser()
        parser.read_string(original.decode("utf-8"))
        major, minor, _ = map(int, parser["general"]["version"].split("."))
        expected = f"{major}.{minor + 1}.0"
        with tempfile.TemporaryDirectory(prefix="Metsä version package ") as folder:
            root = Path(folder)
            root = root / "qgis_plugin"
            root.mkdir()
            copy_help(source, root)
            shutil.copy2(source / "package.ps1", root / "package.ps1")
            target = root / package
            shutil.copytree(source / package, target, ignore=shutil.ignore_patterns("__pycache__"))
            cache = target / "__pycache__" / "unshipped.pyc"
            cache.parent.mkdir()
            cache.write_bytes(b"generated bytecode")
            subprocess.run([POWERSHELL, "-NoProfile", "-ExecutionPolicy", "Bypass", "-File",
                            str(root / "package.ps1"), "-BumpMinor"], capture_output=True, text=True, check=True)
            archive = root / "dist" / f"{package}-{expected}.zip"
            with zipfile.ZipFile(archive) as zipped:
                parser.read_string(zipped.read(package + "/metadata.txt").decode("utf-8"))
                self.assertEqual(parser["general"]["version"], expected)
                self.assertFalse(any("__pycache__" in name or name.endswith((".pyc", ".pyo"))
                                     for name in zipped.namelist()))
                for resource in ("docs/help/manual_fi.html", "docs/help/manual_en.html", "LICENSE",
                                 "THIRD_PARTY_NOTICES", "COMPONENT_INVENTORY.txt", "licenses/CC-BY-4.0.txt"):
                    self.assertIn(package + "/" + resource, zipped.namelist())
            self.assertIn(f"version={expected}", (target / "metadata.txt").read_text(encoding="utf-8"))
            self.assertTrue(cache.exists())
        self.assertEqual((source / package / "metadata.txt").read_bytes(), original)

    def test_current_version_archive_contains_offline_resources_without_caches(self):
        source = Path(__file__).resolve().parents[1]
        package = "savonia_responsible_forest_planning_tool"
        with tempfile.TemporaryDirectory(prefix="Metsä package ") as folder:
            root = Path(folder)
            root = root / "qgis_plugin"
            root.mkdir()
            copy_help(source, root)
            shutil.copy2(source / "package.ps1", root / "package.ps1")
            target = root / package
            shutil.copytree(source / package, target, ignore=shutil.ignore_patterns("__pycache__"))
            cache = target / "analysis" / "__pycache__" / "unshipped.pyc"
            cache.parent.mkdir()
            cache.write_bytes(b"generated bytecode")
            loose_cache = target / "unshipped.pyo"
            loose_cache.write_bytes(b"generated bytecode")
            original = (target / "metadata.txt").read_bytes()
            result = subprocess.run([POWERSHELL, "-NoProfile", "-ExecutionPolicy", "Bypass", "-File",
                                     str(root / "package.ps1")],
                                    capture_output=True, text=True, check=True)
            archives = list((root / "dist").glob("*.zip"))
            self.assertEqual(len(archives), 1, result.stderr)
            archive = archives[0]
            with zipfile.ZipFile(archive) as zipped:
                names = zipped.namelist()
                self.assertEqual({name.split("/")[0] for name in names}, {package})
                self.assertFalse(any("__pycache__" in name or name.endswith((".pyc", ".pyo")) for name in names))
                for resource in ("docs/help/manual_fi.html", "docs/help/manual_en.html", "LICENSE",
                                 "THIRD_PARTY_NOTICES", "COMPONENT_INVENTORY.txt", "licenses/CC-BY-4.0.txt"):
                    self.assertIn(package + "/" + resource, names)
                self.assertEqual(zipped.read(package + "/metadata.txt"), original)
            self.assertEqual((target / "metadata.txt").read_bytes(), original)
            self.assertTrue(cache.exists())
            self.assertTrue(loose_cache.exists())


if __name__ == "__main__":
    unittest.main()
