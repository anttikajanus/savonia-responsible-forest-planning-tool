def selected_language(locale=None):
    """Follow QGIS's application language, using English when unsupported."""
    if locale is None:
        try:
            # Catalog lookup and explicit locales also work outside QGIS.
            from qgis.core import QgsApplication

            locale = QgsApplication.locale()
        except Exception:
            locale = ""
    language = str(locale or "").lower().replace("_", "-").split("-")[0]
    return "fi" if language == "fi" else "en"


def tr(language, key, **values):
    language = language if language in TEXT else "en"
    template = TEXT[language].get(key, TEXT["en"].get(key, key))
    return template.format(**values)


def source_readiness_message(language, result):
    """Translate a language-neutral result from source_readiness.py."""
    reason_code = result.get("reason_code")
    if reason_code == "SOURCE_CONTRACT_MISSING":
        return tr(language, "source_contract_missing")
    if reason_code == "REQUIRED_FIELDS_MISSING":
        return tr(language, "source_schema_fields_missing", fields=", ".join(result.get("missing_fields", ())))
    return ""
